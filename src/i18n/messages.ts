export function translate(locale: Locale, source: string): string {
    if (locale === 'vi') return source;
    return englishMessages[source] || source;
}

const looseEnglishMessages = Object.entries(englishMessages)
    .filter(([source, target]) => source !== target && source.length >= 3)
    .sort(([left], [right]) => right.length - left.length);

/**
 * Safety-net translation for legacy customer UI that has not yet been moved to
 * explicit `t()` calls. Authored product/blog/page HTML is excluded by the DOM
 * bridge so CMS copy is never partially rewritten.
 */
export function translateLoose(locale: Locale, source: string): string {
    if (locale === 'vi' || !source.trim()) return source;
    const exact = englishMessages[source.trim()];
    if (exact) return source.replace(source.trim(), exact);

    let translated = source;
    for (const [vietnamese, english] of looseEnglishMessages) {
        if (translated.includes(vietnamese)) {
            translated = translated.split(vietnamese).join(english);
        }
    }
    return translated;
}

export function interpolate(
    locale: Locale,
    source: string,
    values: Record<string, string | number>,
): string {
    const template = translate(locale, source);
    return Object.entries(values).reduce(
        (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
        template,
    );
}
